import type { NextConfig } from 'next'

/**
 * Baseline security headers on every response.
 *
 * No CSP is set here yet: the site inlines GSAP-driven styles and a Google Maps
 * iframe, so a correct policy needs testing against the real pages rather than a
 * guessed default that silently breaks the map or the reveals. The headers below
 * are the safe, high-value subset that cannot break rendering.
 */
const securityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'SAMEORIGIN' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-DNS-Prefetch-Control', value: 'on' },
  {
    key: 'Strict-Transport-Security',
    value: 'max-age=63072000; includeSubDomains; preload',
  },
  {
    key: 'Permissions-Policy',
    value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()',
  },
]

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: '/:path*', headers: securityHeaders }]
  },
}

export default nextConfig
